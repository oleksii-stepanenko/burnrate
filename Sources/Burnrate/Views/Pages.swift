    @ViewBuilder
    private func scheduleRow(_ what: String, _ every: TimeInterval, _ last: Date?) -> some View {
        GridRow {
            Text(what)
            Text(every < 60 ? "\(Int(every)) s" : "\(Int(every / 60)) min").monospacedDigit()
            Text(last.map { $0.formatted(.relative(presentation: .named)) } ?? "not yet").foregroundStyle(.secondary)
        }
    }

    @ViewBuilder
    private func statRow(_ label: String, _ value: String) -> some View {
        GridRow {
            Text(label).foregroundStyle(.secondary)
            Text(value).textSelection(.enabled)
        }
    }

    @ViewBuilder
    private func sourceRow(_ name: String, _ location: String, _ what: String, exists path: String?) -> some View {
        GridRow(alignment: .top) {
            HStack(spacing: 5) {
                if let path {
                    let ok = FileManager.default.fileExists(atPath: path)
                    Image(systemName: ok ? "checkmark.circle.fill" : "minus.circle").foregroundStyle(ok ? Palette.good : .secondary)
                        .help(ok ? "Found" : "Not found on this Mac")
                } else {
                    Image(systemName: "network").foregroundStyle(.secondary)
                }
                Text(name).fontWeight(.medium)
            }
            VStack(alignment: .leading, spacing: 2) {
                Text(location).font(.caption.monospaced()).foregroundStyle(.secondary).textSelection(.enabled)
                Text(what).fixedSize(horizontal: false, vertical: true)
            }
        }
    }

    @ViewBuilder
    private func tip(_ symbol: String, _ text: String) -> some View {
        Label { Text(text).fixedSize(horizontal: false, vertical: true) } icon: { Image(systemName: symbol).foregroundStyle(Palette.series[0]) }
            .font(.callout)
    }

    private func export() {
        let panel = NSSavePanel()
        panel.allowedContentTypes = [.commaSeparatedText]
        panel.nameFieldStringValue = "token-usage-\(Date().formatted(.iso8601.year().month().day())).csv"
        guard panel.runModal() == .OK, let url = panel.url, let store = app.store else { return }
        Task {
            do {
                let n = try await store.exportCSV(to: url)
                exportMessage = "Exported \(n.formatted()) rows"
            } catch {
                exportMessage = "Export failed: \(error.localizedDescription)"
            }
        }
    }
}
