func plural(_ n: Int, _ word: String) -> String { "\(n) \(word)\(n == 1 ? "" : "s")" }

func sourceLabels(_ csv: String) -> String {
    csv.split(separator: ",").compactMap { Source(rawValue: String($0))?.label }.joined(separator: ", ")
}

