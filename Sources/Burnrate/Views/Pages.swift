// MARK: - Models

struct ModelsPage: View {
    @EnvironmentObject var app: AppState
    @State private var sort = [KeyPathComparator(\ModelRowItem.total, order: .reverse)]
    @State private var selection: String?

    struct ModelRowItem: Identifiable {
        let m: ModelTotal
        var id: String { m.model }
        var name: String { ModelNames.display(m.model) }
        var total: Int { m.totals.all }
        var input: Int { m.totals.input }
        var output: Int { m.totals.output }
        var cacheRead: Int { m.totals.cacheRead }
        var cacheWrite: Int { m.totals.cacheWrite }
        var requests: Int { m.totals.requests }
        var cost: Double { m.totals.cost }
        var lastUsed: Date { m.lastUsed }
    }

    var body: some View {
        let rows = app.data.models.map(ModelRowItem.init).sorted(using: sort)
        VSplitView {
            ScrollView {
                Card(title: selection.map { "\(ModelNames.display($0)) · tokens per \(app.range == .today ? "hour" : "day")" } ?? "Output tokens per model",
                     subtitle: selection == nil ? "Select a model in the table to see its own history" : "Input + output") {
                    if selection != nil {
                        Button { selection = nil } label: { Label("All models", systemImage: "chevron.left") }
                            .controlSize(.small)
                    }
                    UsageChart(points: app.data.buckets, metric: selection == nil ? .output : .inOut,
                               hourly: app.range == .today, focusModel: selection, height: 220)
                }
                .padding(20)
            }
            .frame(minHeight: 320, idealHeight: 380)

            Table(rows, selection: $selection, sortOrder: $sort) {
                TableColumn("Model", value: \.name) { r in
                    HStack(spacing: 6) {
                        Circle().fill(app.color(for: r.m.model)).frame(width: 8, height: 8)
                        Text(r.name).fontWeight(.medium)
                    }
                    .help(r.m.model)
                }
                .width(min: 130, ideal: 170)
                TableColumn("Via") { r in
                    Text(sourceLabels(r.m.sources) + " · " + r.m.providers).foregroundStyle(.secondary).help(r.m.providers)
                }
                .width(min: 110, ideal: 180)
                TableColumn("Requests", value: \.requests) { Text($0.requests.formatted()).monospacedDigit() }.width(66)
                TableColumn("Input", value: \.input) { Text(Fmt.tokens($0.input)).monospacedDigit() }.width(62)
                TableColumn("Output", value: \.output) { Text(Fmt.tokens($0.output)).monospacedDigit() }.width(62)
                TableColumn("Cache read", value: \.cacheRead) { Text(Fmt.tokens($0.cacheRead)).monospacedDigit() }.width(76)
                TableColumn("Cache write", value: \.cacheWrite) { Text(Fmt.tokens($0.cacheWrite)).monospacedDigit() }.width(76)
                TableColumn("Total", value: \.total) { Text(Fmt.tokens($0.total)).monospacedDigit().fontWeight(.medium) }.width(66)
                TableColumn("Est. cost", value: \.cost) { Text(Fmt.cost($0.cost)).monospacedDigit() }.width(66)
                TableColumn("Last used", value: \.lastUsed) { Text($0.lastUsed, format: .relative(presentation: .named)).foregroundStyle(.secondary) }
                    .width(min: 80, ideal: 100)
            }
            .frame(minHeight: 200)
        }
    }
}

// MARK: - Sessions

struct SessionsPage: View {
    @EnvironmentObject var app: AppState
    @State private var sort = [KeyPathComparator(\SessionSummary.end, order: .reverse)]
    @State private var selection: SessionSummary.ID?

    var body: some View {
        let search = app.sessionSearch
        let rows = app.data.sessions.filter { s in
            search.isEmpty || [s.title ?? "", s.project, s.id, s.models.joined(separator: " ")]
                .contains { $0.localizedCaseInsensitiveContains(search) }
        }.sorted(using: sort)

        Table(rows, selection: $selection, sortOrder: $sort) {
            TableColumn("") { s in
                Circle().fill(s.isActive ? Palette.good : Color.clear).frame(width: 7, height: 7)
                    .helpIfPresent(s.isActive ? "Active in the last 10 minutes" : nil)
            }
            .width(12)
            TableColumn("Session") { s in
                Text(s.displayTitle).lineLimit(1).help(s.displayTitle)
            }
            .width(min: 140, ideal: 230)
            TableColumn("Project") { Text($0.projectName).helpIfPresent($0.project) }.width(min: 70, ideal: 110)
            TableColumn("Agent") { s in Label(s.source.shortLabel, systemImage: s.source.symbol) }.width(min: 70, ideal: 80)
            TableColumn("Models") { s in
                HStack(spacing: 4) {
                    ForEach(s.models.prefix(2), id: \.self) { m in
                        Text(ModelNames.display(m)).font(.caption).lineLimit(1)
                            .padding(.horizontal, 5).padding(.vertical, 1)
                            .background(Capsule().fill(app.color(for: m).opacity(0.18)))
                    }
                    if s.models.count > 2 { Text("+\(s.models.count - 2)").font(.caption).foregroundStyle(.secondary) }
                }
                .help(s.models.map(ModelNames.display).joined(separator: ", "))
            }
            .width(min: 90, ideal: 130)
            TableColumn("Last active", value: \.end) { Text($0.end, format: .dateTime.month(.abbreviated).day().hour().minute()).monospacedDigit() }
                .width(min: 95, ideal: 110)
            TableColumn("Duration", value: \.duration) { Text(Fmt.duration($0.duration)).monospacedDigit() }.width(62)
            TableColumn("Req.", value: \.requests) { Text("\($0.requests)").monospacedDigit() }.width(44)
            TableColumn("Tokens", value: \.tokens) { Text(Fmt.tokens($0.tokens)).monospacedDigit() }.width(60)
            TableColumn("Cost", value: \.cost) { Text(Fmt.cost($0.cost)).monospacedDigit() }.width(60)
        }
        .searchable(text: $app.sessionSearch, prompt: "Title, project, model…")
        .overlay {
            if rows.isEmpty {
                ContentUnavailableView.search(text: search)
            }
        }
        .inspector(isPresented: Binding(get: { selection != nil }, set: { if !$0 { selection = nil } })) {
            if let s = rows.first(where: { $0.id == selection }) ?? app.data.sessions.first(where: { $0.id == selection }) {
                SessionInspector(session: s)
                    .inspectorColumnWidth(min: 280, ideal: 320, max: 420)
            }
        }
    }
}

struct SessionInspector: View {
    @EnvironmentObject var app: AppState
    let session: SessionSummary
    @State private var detail = SessionDetail()

    var body: some View {
        ScrollView {
            VStack(alignment: .leading, spacing: 16) {
                VStack(alignment: .leading, spacing: 4) {
                    HStack {
                        Label(session.source.label, systemImage: session.source.symbol).font(.caption).foregroundStyle(.secondary)
                        if session.isActive {
                            Text("Active").font(.caption2.weight(.semibold)).foregroundStyle(Palette.good)
                        }
                    }
                    Text(session.displayTitle).font(.title3.weight(.semibold)).textSelection(.enabled)
                    Text(session.id).font(.caption2.monospaced()).foregroundStyle(.tertiary).textSelection(.enabled)
                }

                Grid(alignment: .leading, horizontalSpacing: 12, verticalSpacing: 6) {
                    row("Project", detail.cwd ?? session.project)
                    row("Started", session.start.formatted(date: .abbreviated, time: .shortened))
                    row("Last active", session.end.formatted(date: .abbreviated, time: .shortened))
                    row("Duration", Fmt.duration(session.duration))
                    row("Requests", session.requests.formatted())
                    row("Tokens", "\(Fmt.tokens(session.tokens)) (\(Fmt.tokens(session.output)) output)")
                    row("Est. cost", Fmt.cost(session.cost))
                    if !detail.kinds.isEmpty {
                        row("Calls", detail.kinds.map { "\($0.count) \($0.name)" }.joined(separator: " · "))
                    }
                }
                .font(.callout)

                if !detail.models.isEmpty {
                    Text("Models").font(.headline)
                    RankedBars(items: detail.models.map {
                        .init(id: $0.model, label: ModelNames.display($0.model), value: Double($0.totals.all),
                              valueText: "\(Fmt.tokens($0.totals.all)) · \(Fmt.cost($0.totals.cost))",
                              color: app.namedModels.contains($0.model) ? app.color(for: $0.model) : Palette.other,
                              help: "in \(Fmt.tokens($0.totals.input)) · out \(Fmt.tokens($0.totals.output)) · cache read \(Fmt.tokens($0.totals.cacheRead)) · cache write \(Fmt.tokens($0.totals.cacheWrite))")
                    })
                }
                if !detail.tools.isEmpty {
                    Text("Tools").font(.headline)
                    RankedBars(items: detail.tools.prefix(12).map {
                        .init(id: $0.name, label: $0.name, value: Double($0.count), valueText: "\($0.count)", color: Palette.series[2])
                    })
                }
            }
            .padding(16)
            .frame(maxWidth: .infinity, alignment: .leading)
        }
        .task(id: session.id) {
            if let store = app.store { detail = await store.sessionDetail(session.id) }
        }
    }

    @ViewBuilder
    private func row(_ label: String, _ value: String) -> some View {
        GridRow {
            Text(label).foregroundStyle(.secondary)
            Text(value).textSelection(.enabled).lineLimit(3)
        }
    }
}

